/// <summary>
/// 가이드 퀘스트를 얼마나 보여줄지. 조언자 퀘스트에서 고르고 설정 메뉴에서 언제든 바꾼다.
///
/// 정수로 저장되므로(PlayerPrefs·GuideQuestSO.Choice) <b>새 값은 반드시 끝에 추가한다</b> -
/// 중간에 끼우면 이미 저장된 플레이어 설정과 만들어 둔 선택지 에셋이 다른 수준을 가리킨다
/// (HelpCategory·TutorialBuildingKind와 같은 규칙).
///
/// 어느 수준이든 <b>완료 판정은 항상 돌아간다</b> - 나중에 켰을 때 이미 한 일이 체크돼 있어야 하기 때문이다.
/// 수준이 가르는 것은 "무엇을 보여주는가"뿐이다.
/// </summary>
public enum GuideLevel
{
    // 우상단 카드 + 목록 + 말풍선·딤 강조. 기본값이다.
    Full = 0,

    // 목록 + 한 줄 토스트만. 카드로 화면을 멈춰 세우지 않는다.
    TipsOnly,

    // 아무것도 띄우지 않는다. 조언자 카드만은 예외로 한 번 뜬다 - 그것이 이 값을 고르는 창구다.
    Off,
}

// 건물 하나에 걸린 지역 효과의 종류. 건물 위 표식(UI_BuildingEffectBadge) 한 칸에 대응한다.
//
// 지형이 아니라 "효과"를 단위로 나눈다 - 건물이 설원과 암석에 걸쳐 있어도 플레이어가 알아야 할
// 것은 "나무와 돌을 함께 낸다"이지 "두 지형에 걸쳐 있다"가 아니기 때문이다. 지형 자체는 타일로
// 이미 보인다.
//
// 코드베이스에서 "상태이상"은 몬스터가 타워/용에게 거는 효과(Combat/Status)를 가리키므로,
// 건물 쪽은 "건물 효과(BuildingEffect)"로 부른다.
//
// 선언 순서 = 표식이 그려지는 순서다(치명적인 것부터). 조회는 인덱스가 아니라 엔트리 배열
// (BuildingEffectIconData)이므로 순서를 바꿔도 데이터가 어긋나지 않는다.
public enum BuildingEffectKind
{
    Suspended, // 운영 중단 - 인구 배치 불가 (화산 지대에서 얼음 새끼용의 건설 허가가 사라짐)
    YieldDown, // 생산량 감소
    AttackSpeedDown, // 타워 공격속도 감소
    WoodUpkeep, // 배치 인구에 비례해 매일 소모하는 나무
    StoneUpkeep, // 배치 인구에 비례해 매일 소모하는 돌
}

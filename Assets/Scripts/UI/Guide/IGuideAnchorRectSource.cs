/// <summary>
/// 가리킬 자리를 스스로 계산해 자기 사각형에 담아 두는 앵커.
///
/// 이 계산을 <c>LateUpdate</c>에 두면 안내와 순서를 다툰다 - Unity는 LateUpdate끼리의 순서를
/// 보장하지 않으므로 앵커가 안내 뒤에 돌면 그 프레임의 구멍이 <b>한 컷 옛 크기</b>로 뚫린다.
/// 대상이 매 프레임 조금씩 움직이는 앵커는 그래도 눈에 띄지 않지만, 사각형이 <b>불연속으로</b>
/// 바뀌는 앵커는 그 한 프레임 동안 눌러야 할 것이 딤 밖에 남아 클릭이 막힌다.
///
/// 그래서 순서에 맡기지 않고 <see cref="UI_GuideOverlay"/>가 사각형을 <b>읽기 직전에</b> 당겨 온다.
/// 안내가 지금 가리키는 대상에게만 부르므로, 구현체는 "지금 내가 쓰이는가"를 따로 볼 필요가 없다.
/// 대신 <b>꺼져 있어도 이 호출은 도달한다</b>(GetComponent는 비활성 컴포넌트도 준다) -
/// 배선 실패로 스스로를 끄는 구현체는 <c>enabled</c>를 직접 봐야 한다.
/// </summary>
public interface IGuideAnchorRectSource
{
    void RefreshAnchorRect();
}

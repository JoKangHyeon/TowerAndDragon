/// <summary>
/// 말풍선을 띄울 자리. 대상을 따라다니게 하지 않고 미리 정해둔 몇 곳 중 하나를 고른다 -
/// 대상마다 크기·위치가 달라 자동 배치는 복잡도 대비 이득이 적고, 안내가 어디를 가리키는지는 스포트라이트가 알려준다.
/// 실제 좌표는 씬에서 잡으므로(UI_GuideOverlay의 슬롯 필드) 코드는 위치를 계산하지 않는다.
///
/// 기본 자리가 이미 화면 위쪽이라 별도의 "위" 자리는 두지 않는다.
/// </summary>
public enum GuideBubbleSlot
{
    // 씬에 놓은 기본 자리. 대부분의 단계가 이걸 쓴다.
    Default = 0,

    // 가리킬 대상도 열어 둔 패널도 없는 순수 설명용. 가릴 것이 없으니 가장 잘 보이는 한가운데에 띄운다.
    Center,

    // 그리드를 가리면 안 되는 단계용(타일을 클릭해 배치하라는 안내 등).
    Bottom,
}

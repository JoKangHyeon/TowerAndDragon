/// <summary>
/// 건물을 놓지 못한 이유. 배치가 이미 실패한 뒤에 "왜 실패했는지"만 되묻는 진단용이다 -
/// 가능/불가 판정 자체는 GridMap.CanConstructBuildingFootprint가 그대로 담당한다.
/// 판정을 두 번 구현하지 않으므로 안내와 실제 배치 결과가 어긋날 수 없다.
///
/// 값의 순서가 그대로 안내 우선순위다(뒤로 갈수록 낮음) - 풋프린트의 여러 칸이 서로 다른 이유로
/// 막혔을 때 가장 앞선 사유 하나만 알린다.
/// </summary>
public enum PlacementBlockReason
{
    None,

    // 절벽·물·길·용암 등 지형이 막았다. 용암인지 여부는 호출부가 한 번 더 확인해 문구를 나눈다.
    BlockedByTerrain,

    // 다른 건물이 이미 차지한 칸이다.
    Occupied,

    // 아직 점령하지 않은 청크다.
    NotConquered,

    // 지형·점유·점령은 모두 통과했지만 생산시설이 요구하는 자원 노드가 없다.
    MissingResourceNode,

    // 봉인석을 세울 수 있는 자리가 아니다(포탈 영역 밖이거나, 그 포탈에 이미 봉인석이 있다).
    NotSealSite,

    // 맵 밖 좌표. 플레이어가 취할 행동이 없어 안내하지 않는다.
    //
    // 반드시 맨 뒤여야 한다 - 맵 경계에 걸친 풋프린트에서 이게 앞서면 형제 칸의 실행 가능한
    // 사유(용암·점유 등)를 덮어 아무 안내도 못 하게 된다.
    OutOfGrid,
}

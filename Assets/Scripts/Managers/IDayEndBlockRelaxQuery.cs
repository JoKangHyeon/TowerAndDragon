/// <summary>
/// 밤 버튼을 눌렀는데 관문에 막혔을 때, 그 관문을 지금 접을 수 있는지 묻는다.
/// <see cref="IDayEndBlockQuery"/>로 등록된 대상 중 이것도 구현한 쪽에게만 묻는다.
///
/// 있는 이유: 관문 중에는 "아직 안 된다"가 아니라 <b>"조금만 기다려 달라"</b>인 것이 있다.
/// 튜토리얼 챕터가 끝나고 마지막 안내를 읽을 틈을 두는 구간이 그렇다 - 화면은 이미 비었는데
/// 관문만 남아, 다 읽고 버튼을 누른 플레이어에게 "안내가 끝나면 넘어갈 수 있습니다"라는
/// 거짓말이 뜬다. 버튼을 눌렀다는 것이 곧 다 읽었다는 답이므로 그 틈은 여기서 접는다.
///
/// 접었다고 반드시 밤이 오는 것은 아니다. 접은 자리에서 다음 챕터가 곧바로 관문을 다시 걸 수 있고,
/// 그때는 막히는 것이 맞다 - 그래서 부르는 쪽은 접은 뒤 관문을 <b>다시</b> 확인해야 한다.
/// </summary>
public interface IDayEndBlockRelaxQuery
{
    bool TryRelaxDayEndBlock();
}

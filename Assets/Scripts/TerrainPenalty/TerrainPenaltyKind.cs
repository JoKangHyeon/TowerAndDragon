// 지역(지형) 페널티의 종류. 외부 완화 소스(새끼용 등)가 "어떤 페널티를 얼마나 완화하는지"를
// 지정하는 데 쓴다 - 예를 들어 얼음 새끼용이 설원의 나무 유지비만 깎고 사막 생산 페널티는
// 건드리지 않는 식의 구분이 가능해야 하기 때문이다.
public enum TerrainPenaltyKind
{
    Yield, // 건물 생산량 감소
    TowerAttackSpeed, // 타워 공격속도 감소
    WoodUpkeep, // 배치 인구 1명당 매일 추가 소모하는 나무
    StoneUpkeep, // 배치 인구 1명당 매일 추가 소모하는 돌
}
